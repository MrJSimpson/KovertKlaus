#!/usr/bin/env node
/**
 * Tier 1 (what): Writes THIRD_PARTY_NOTICES.md: every production dependency in
 * package-lock.json with its version and license, followed by each package's
 * license text from node_modules. `--check` fails when the package table is stale.
 * Tier 2 (why): MIT, BSD, ISC, Apache-2.0, CC-BY-4.0, EPL-2.0 and LGPL all require
 * their notices to travel with copies (the Docker image ships node_modules; the
 * static export ships bundled code). Generating from the lockfile keeps the list
 * exact, and the CI check keeps it current after every dependency bump.
 * Tier 3 (how): The table comes from the lockfile only (no `dev` flag), so it is
 * the same on every OS, which is what `--check` compares. License texts are read
 * from node_modules when installed; platform-only packages missing locally are
 * listed with their SPDX id. `devOptional` packages count: npm installs them
 * under `--omit=dev` when a production package needs them optionally.
 */
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const root = process.cwd();
const OUT = join(root, 'THIRD_PARTY_NOTICES.md');
const lock = JSON.parse(readFileSync(join(root, 'package-lock.json'), 'utf8'));

const pkgs = Object.entries(lock.packages)
  .filter(([path, p]) => path.startsWith('node_modules/') && !p.dev && !p.link)
  .map(([path, p]) => ({
    path,
    name: p.name ?? path.slice(path.lastIndexOf('node_modules/') + 'node_modules/'.length),
    version: p.version,
    license: typeof p.license === 'string' ? p.license : 'SEE PACKAGE',
    optional: Boolean(p.optional || p.devOptional),
  }))
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version, undefined, { numeric: true }));

// One row per name@version (nested copies of the same version are listed once).
const unique = [...new Map(pkgs.map((p) => [`${p.name}@${p.version}`, p])).values()];

const TABLE_START = '<!-- table:start -->';
const TABLE_END = '<!-- table:end -->';
const escape = (s) => s.replace(/\|/g, '\\|');
const table = [
  TABLE_START,
  '| Package | Version | License |',
  '| :--- | :--- | :--- |',
  ...unique.map((p) => `| \`${escape(p.name)}\`${p.optional ? ' (platform-specific)' : ''} | ${p.version} | ${escape(p.license)} |`),
  TABLE_END,
].join('\n');

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  const start = current.indexOf(TABLE_START);
  const end = current.indexOf(TABLE_END);
  const existing = start >= 0 && end > start ? current.slice(start, end + TABLE_END.length) : '';
  if (existing !== table) {
    console.error('THIRD_PARTY_NOTICES.md is out of date. Run `npm run notices` and commit the result.');
    process.exit(1);
  }
  console.log(`THIRD_PARTY_NOTICES.md is current (${unique.length} packages).`);
  process.exit(0);
}

const LICENSE_FILE = /^(licen[cs]e|copying|notice)(\.|-|$)/i;
// Packages with an identical license text (e.g. one vendor's scoped packages) share one block.
const groups = new Map();
for (const p of unique) {
  const dir = join(root, p.path);
  let key;
  if (!existsSync(dir)) {
    key = `${p.license}. Not installed on the machine that generated this file (platform-specific); see the package for its license text.`;
  } else {
    const files = readdirSync(dir).filter((f) => LICENSE_FILE.test(f)).sort();
    const body = files.map((f) => readFileSync(join(dir, f), 'utf8').trim().replace(/\r\n/g, '\n')).join('\n\n');
    key = body ? '```text\n' + body.replace(/```/g, "'''") + '\n```' : `${p.license}. The package ships no separate license file.`;
  }
  if (!groups.has(key)) groups.set(key, []);
  groups.get(key).push(`${p.name}@${p.version}`);
}
const texts = [...groups].map(([body, names]) => `### ${names.join(', ')}\n\n${body}`);

const doc = `# Third-Party Notices

KovertKlaus itself is licensed under [\`LICENSE.md\`](./LICENSE.md). It depends on the open-source packages below, each under its own license. This file is generated by \`npm run notices\` from \`package-lock.json\`; do not edit it by hand.

## Project-owned assets

- The spot illustrations and artwork in \`public/\` are original works made for KovertKlaus and are covered by \`LICENSE.md\`.

## Production dependencies (${unique.length})

${table}

## License texts

${texts.join('\n\n')}
`;

writeFileSync(OUT, doc);
console.log(`Wrote THIRD_PARTY_NOTICES.md (${unique.length} packages).`);
